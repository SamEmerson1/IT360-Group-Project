import argparse
import os
import sys
import traceback

# Make sibling modules importable when the script is invoked as
# `python src/main.py` from the repository root.
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from evidence import AuditLog, compute_hashes, verify_integrity, utc_now
from email_parser import parse_email, EmailParseError
from header_analysis import analyze_headers
from url_analysis import analyze_urls
from attachment_analysis import analyze_attachments
from scoring import score_findings
from ai_summary import generate_summary
from report import (
    print_console_report,
    write_json_report,
    write_ioc_csv,
    write_html_report,
)

VERSION = "1.0.0"

# File extensions treated as email evidence when scanning a directory.
EMAIL_EXTENSIONS = (".eml", ".msg")


def analyze_file(path, audit_log=None, enable_ai=True):
    """Run the complete analysis pipeline against a single email file.

    Args:
        path (str): Path to the evidence file.
        audit_log (AuditLog | None): Optional audit log.
        enable_ai (bool): Whether to request an AI summary.

    Returns:
        dict: The complete analysis result, suitable for any report writer.

    Raises:
        FileNotFoundError, EmailParseError: On unrecoverable input problems.
    """
    if audit_log:
        audit_log.record("EVIDENCE_OPENED", f"Beginning analysis of {path}")

    # --- 1. Hash before doing anything else ---------------------------------
    hashes_before = compute_hashes(path)
    if audit_log:
        audit_log.record(
            "HASH_BEFORE",
            f"MD5: {hashes_before['md5']} SHA-256: {hashes_before['sha256']} "
            f"({hashes_before['size_bytes']} bytes)",
        )

    # --- 2. Parse -----------------------------------------------------------
    parsed = parse_email(path, audit_log=audit_log)

    # --- 3-5. Analysis modules ---------------------------------------------
    header_results = analyze_headers(parsed, audit_log=audit_log)
    url_results = analyze_urls(parsed, audit_log=audit_log)
    attachment_results = analyze_attachments(parsed, audit_log=audit_log)

    all_findings = (
        header_results["findings"]
        + url_results["findings"]
        + attachment_results["findings"]
    )

    # --- 6. Score -----------------------------------------------------------
    risk = score_findings(all_findings)
    if audit_log:
        audit_log.record(
            "RISK_SCORED",
            f"{risk['band']} ({risk['score']}/100) -- "
            f"{risk['counts']['high']} high, {risk['counts']['medium']} medium, "
            f"{risk['counts']['low']} low",
        )

    # Assemble the result before the AI step, since the AI module consumes it.
    analysis = {
        "tool": "Phishing Email Forensics Analyzer",
        "version": VERSION,
        "generated_at": utc_now(),
        "evidence": {
            "path": os.path.abspath(path),
            "filename": os.path.basename(path),
            "format": parsed["format"],
            "hashes_before": hashes_before,
        },
        "headers": header_results,
        "urls": url_results,
        "attachments": attachment_results,
        "all_findings": all_findings,
        "risk": risk,
    }

    # --- 7. AI summary ------------------------------------------------------
    if enable_ai:
        analysis["ai_summary"] = generate_summary(analysis, audit_log=audit_log)
    else:
        analysis["ai_summary"] = {
            "available": False,
            "text": None,
            "model": None,
            "error": "AI summary disabled by --no-ai flag.",
        }

    # --- 8. Verify integrity ------------------------------------------------
    hashes_after = compute_hashes(path)
    integrity = verify_integrity(hashes_before, hashes_after)
    analysis["evidence"]["hashes_after"] = hashes_after
    analysis["integrity"] = integrity

    if audit_log:
        audit_log.record(
            "HASH_AFTER",
            f"MD5: {hashes_after['md5']} SHA-256: {hashes_after['sha256']}",
        )
        audit_log.record(
            "INTEGRITY_CHECK",
            integrity["message"],
        )

    return analysis


def collect_input_files(input_path):
    """Resolve the --input argument into a list of files to analyze.

    Accepts either a single file or a directory. Directories are scanned
    non-recursively for files with email extensions.
    """
    if os.path.isfile(input_path):
        return [input_path]

    if os.path.isdir(input_path):
        entries = sorted(
            os.path.join(input_path, name)
            for name in os.listdir(input_path)
            if name.lower().endswith(EMAIL_EXTENSIONS)
        )
        return entries

    raise FileNotFoundError(f"Input path does not exist: {input_path}")


def build_parser():
    """Construct the command-line argument parser."""
    parser = argparse.ArgumentParser(
        prog="phishing-analyzer",
        description=(
            "Analyze suspicious email files for indicators of phishing. "
            "Reconstructs the delivery path, evaluates sender authentication, "
            "extracts and defangs URLs, hashes attachments, and produces a "
            "structured forensic report."
        ),
        epilog=(
            "IT 360 Final Project -- Tyler and Sam. "
            "This tool performs no network activity during analysis except for "
            "the optional AI summary request."
        ),
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )

    parser.add_argument(
        "-i", "--input", required=True, metavar="PATH",
        help="Email file (.eml or .msg) or a directory of them.",
    )
    parser.add_argument(
        "-o", "--output", default="reports", metavar="DIR",
        help="Directory for generated reports. Default: reports/",
    )
    parser.add_argument(
        "-f", "--format", default="console",
        choices=["console", "json", "csv", "html", "all"],
        help=("Output format. 'console' prints to the terminal only; 'all' "
              "writes JSON, CSV, and HTML in addition to the console output. "
              "Default: console"),
    )
    parser.add_argument(
        "--no-ai", action="store_true",
        help="Skip the AI-generated summary. All other analysis is unaffected.",
    )
    parser.add_argument(
        "--model", default=None, metavar="MODEL_ID",
        help="Override the model used for the AI summary.",
    )
    parser.add_argument(
        "--audit-log", default=None, metavar="PATH",
        help=("Write a timestamped audit log to this path. Default: "
              "<output>/audit.log"),
    )
    parser.add_argument(
        "-q", "--quiet", action="store_true",
        help="Suppress the console report. Useful when writing files only.",
    )
    parser.add_argument(
        "--no-color", action="store_true",
        help="Disable ANSI color in console output.",
    )
    parser.add_argument(
        "--version", action="version",
        version=f"Phishing Email Forensics Analyzer {VERSION}",
    )

    return parser


def main(argv=None):
    """Program entry point. Returns the process exit code."""
    parser = build_parser()
    args = parser.parse_args(argv)

    # Color is disabled automatically when stdout is redirected, so that piping
    # to a file or another program produces clean text.
    use_color = not args.no_color and sys.stdout.isatty()

    if args.model:
        os.environ["PHISH_ANALYZER_MODEL"] = args.model

    # --- Resolve inputs -----------------------------------------------------
    try:
        files = collect_input_files(args.input)
    except FileNotFoundError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2

    if not files:
        print(f"error: no .eml or .msg files found in {args.input}",
              file=sys.stderr)
        return 2

    os.makedirs(args.output, exist_ok=True)
    audit_path = args.audit_log or os.path.join(args.output, "audit.log")

    write_files = args.format in ("json", "csv", "html", "all")
    flagged_count = 0
    failed_count = 0

    with AuditLog(audit_path) as audit_log:
        audit_log.record(
            "RUN_START",
            f"Analyzer v{VERSION} starting. {len(files)} file(s) queued. "
            f"AI summary: {'disabled' if args.no_ai else 'enabled'}.",
        )

        for path in files:
            try:
                analysis = analyze_file(
                    path, audit_log=audit_log, enable_ai=not args.no_ai
                )
            except (EmailParseError, FileNotFoundError) as exc:
                # Expected, recoverable failures. Report and move on so that one
                # bad file in a batch does not abort the whole run.
                failed_count += 1
                print(f"error: {os.path.basename(path)}: {exc}", file=sys.stderr)
                audit_log.record("ANALYSIS_FAILED", f"{path}: {exc}")
                continue
            except Exception as exc:
                # Unexpected failure. Same handling, but we record the traceback
                # so the problem can actually be debugged later.
                failed_count += 1
                print(f"error: {os.path.basename(path)}: unexpected failure: "
                      f"{type(exc).__name__}: {exc}", file=sys.stderr)
                audit_log.record(
                    "ANALYSIS_ERROR",
                    f"{path}: {type(exc).__name__}: {exc}\n"
                    f"{traceback.format_exc()}",
                )
                continue

            if analysis["risk"]["band"] in ("SUSPICIOUS", "MALICIOUS"):
                flagged_count += 1

            # --- Console ----------------------------------------------------
            if not args.quiet:
                print_console_report(analysis, use_color=use_color)

            # --- Files ------------------------------------------------------
            if write_files:
                stem = os.path.splitext(os.path.basename(path))[0]

                if args.format in ("json", "all"):
                    out = write_json_report(
                        analysis, os.path.join(args.output, f"{stem}.json"))
                    audit_log.record("REPORT_WRITTEN", f"JSON: {out}")
                    if not args.quiet:
                        print(f"  wrote {out}")

                if args.format in ("csv", "all"):
                    out, count = write_ioc_csv(
                        analysis, os.path.join(args.output, f"{stem}_iocs.csv"))
                    audit_log.record(
                        "REPORT_WRITTEN", f"CSV: {out} ({count} indicators)")
                    if not args.quiet:
                        print(f"  wrote {out} ({count} indicators)")

                if args.format in ("html", "all"):
                    out = write_html_report(
                        analysis, os.path.join(args.output, f"{stem}.html"))
                    audit_log.record("REPORT_WRITTEN", f"HTML: {out}")
                    if not args.quiet:
                        print(f"  wrote {out}")

                if not args.quiet:
                    print()

        audit_log.record(
            "RUN_COMPLETE",
            f"{len(files) - failed_count} analyzed, {failed_count} failed, "
            f"{flagged_count} flagged as SUSPICIOUS or MALICIOUS.",
        )

    # --- Batch summary ------------------------------------------------------
    if len(files) > 1 and not args.quiet:
        print(f"Processed {len(files)} file(s): "
              f"{flagged_count} flagged, {failed_count} failed.")
        print(f"Audit log: {audit_path}")

    if failed_count and failed_count == len(files):
        return 2
    return 1 if flagged_count else 0


if __name__ == "__main__":
    sys.exit(main())
