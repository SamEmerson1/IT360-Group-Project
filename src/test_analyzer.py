def test_defang():
    print("\nDefanging:")
    check("https scheme is neutralized",
          defang("https://evil.com/x") == "hxxps://evil[.]com/x")
    check("http scheme is neutralized",
          defang("http://evil.com") == "hxxp://evil[.]com")
    check("dots in the path are left alone",
          defang("https://a.com/file.pdf") == "hxxps://a[.]com/file.pdf")
    check("empty input returns empty string", defang("") == "")


def test_unwrap():
    print("\nURL unwrapping:")
    safelinks = ("https://na01.safelinks.protection.outlook.com/"
                 "?url=https%3A%2F%2Fbad.example%2Fx&data=05")
    url, wrapper = unwrap_url(safelinks)
    check("Safe Links target is recovered", url == "https://bad.example/x")
    check("Safe Links wrapper is identified", wrapper == "Microsoft Safe Links")

    url, wrapper = unwrap_url("https://normal.example/page")
    check("ordinary URLs pass through unchanged",
          url == "https://normal.example/page" and wrapper is None)


def test_magic_bytes():
    print("\nMagic byte identification:")
    check("PE executable is identified",
          "Windows executable" in (identify_by_magic(b"MZ\x90\x00") or ""))
    check("PDF is identified",
          identify_by_magic(b"%PDF-1.7") == "PDF document")
    check("PNG is identified",
          identify_by_magic(b"\x89PNG\r\n\x1a\n") == "PNG image")
    check("ZIP is identified",
          "ZIP" in (identify_by_magic(b"PK\x03\x04") or ""))
    check("unknown content returns None",
          identify_by_magic(b"nothing recognizable here") is None)
    check("empty input returns None", identify_by_magic(b"") is None)


def test_levenshtein():
    print("\nEdit distance:")
    check("identical strings score 0", _levenshtein("paypal", "paypal") == 0)
    check("single substitution scores 1", _levenshtein("paypa1", "paypal") == 1)
    check("single deletion scores 1", _levenshtein("payal", "paypal") == 1)
    check("empty vs non-empty scores the length",
          _levenshtein("", "abcd") == 4)


def test_lookalike():
    print("\nLookalike domains:")
    findings = check_lookalike_domain("paypa1.com")
    check("typosquatted domain is flagged",
          any(f["code"] == "LOOKALIKE_DOMAIN" for f in findings))

    findings = check_lookalike_domain("paypal.com")
    check("the legitimate domain is not flagged",
          not any(f["code"] == "LOOKALIKE_DOMAIN" for f in findings))

    findings = check_lookalike_domain("xn--pypal-4ve.com")
    check("punycode is flagged",
          any(f["code"] == "PUNYCODE_DOMAIN" for f in findings))

    findings = check_lookalike_domain("microsoft-account-verify.tk")
    check("brand name in an unrelated domain is flagged",
          any(f["code"] == "BRAND_IN_UNRELATED_DOMAIN" for f in findings))


def test_scoring():
    print("\nRisk scoring:")
    result = score_findings([])
    check("no findings produces LOW RISK",
          result["band"] == "LOW RISK" and result["score"] == 0)

    result = score_findings([{"code": "X", "severity": "high"}])
    check("one high finding reaches at least SUSPICIOUS",
          result["band"] in ("SUSPICIOUS", "MALICIOUS"))

    result = score_findings([
        {"code": "A", "severity": "high"},
        {"code": "B", "severity": "high"},
        {"code": "C", "severity": "high"},
    ])
    check("three high findings reach MALICIOUS", result["band"] == "MALICIOUS")

    result = score_findings([{"code": "X", "severity": "high"}] * 20)
    check("score is capped at 100", result["score"] == 100)

    result = score_findings([
        {"code": "DMARC_FAIL", "severity": "high"},
        {"code": "ANCHOR_TEXT_MISMATCH", "severity": "high"},
    ])
    check("correlation bonus fires for auth failure plus deception",
          result["bonus_points"] > 0)


