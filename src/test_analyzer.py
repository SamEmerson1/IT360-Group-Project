_HERE = os.path.dirname(os.path.abspath(__file__))
DATA_DIR = os.path.join(os.path.dirname(_HERE), "data")

# Test results accumulate here so we can print a summary at the end.
_passed = 0
_failed = 0


def check(description, condition):
    """Assert a condition and record the result."""
    global _passed, _failed
    if condition:
        _passed += 1
        print(f"  PASS  {description}")
    else:
        _failed += 1
        print(f"  FAIL  {description}")


def codes_for(sample_name):
    """Analyze a sample and return the set of finding codes it produced."""
    path = os.path.join(DATA_DIR, sample_name)
    analysis = analyze_file(path, audit_log=None, enable_ai=False)
    return {f["code"] for f in analysis["all_findings"]}, analysis


