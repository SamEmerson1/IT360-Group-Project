# Domains that are impersonated often enough to be worth checking against.
# This list is deliberately short and editable. A production tool would pull
# from a maintained brand-protection feed; for a course project a static list
# demonstrates the technique without pretending to be exhaustive.
COMMONLY_IMPERSONATED = [
    "paypal.com", "microsoft.com", "office365.com", "outlook.com",
    "google.com", "gmail.com", "apple.com", "icloud.com",
    "amazon.com", "netflix.com", "facebook.com", "instagram.com",
    "linkedin.com", "dropbox.com", "docusign.com", "adobe.com",
    "chase.com", "bankofamerica.com", "wellsfargo.com", "citibank.com",
    "usps.com", "fedex.com", "ups.com", "dhl.com",
    "irs.gov", "ssa.gov",
]

# Free mail providers. Not suspicious on their own, but a message that claims
# to be from a corporation while originating from a free provider is worth
# flagging.
FREE_MAIL_PROVIDERS = {
    "gmail.com", "yahoo.com", "hotmail.com", "outlook.com", "aol.com",
    "protonmail.com", "proton.me", "mail.com", "gmx.com", "yandex.com",
    "icloud.com", "zoho.com", "tutanota.com",
}

# Corporate-sounding words that, when they appear in a display name paired with
# a free-mail sending address, suggest impersonation.
CORPORATE_DISPLAY_TERMS = [
    "support", "security", "helpdesk", "help desk", "it department",
    "admin", "administrator", "billing", "payroll", "hr", "human resources",
    "no-reply", "noreply", "notification", "alert", "service desk",
    "account", "verification", "team",
]

# Regex for pulling structured data out of a Received: header. Received headers
# are notoriously inconsistent between mail servers, so these patterns are
# tolerant and any individual capture may come back empty.
_RECEIVED_FROM = re.compile(r"\bfrom\s+([^\s;()]+)", re.IGNORECASE)
_RECEIVED_BY = re.compile(r"\bby\s+([^\s;()]+)", re.IGNORECASE)
_RECEIVED_WITH = re.compile(r"\bwith\s+([^\s;()]+)", re.IGNORECASE)
_RECEIVED_IP = re.compile(r"\[?\b((?:\d{1,3}\.){3}\d{1,3})\b\]?")
_RECEIVED_DATE = re.compile(r";\s*(.+)$")

# Authentication-Results parsing. Format is defined by RFC 8601 but adherence
# varies, so we search for each method independently rather than parsing the
# header as a strict grammar.
_AUTH_METHOD = re.compile(
    r"\b(spf|dkim|dmarc|compauth)\s*=\s*(\w+)", re.IGNORECASE
)


