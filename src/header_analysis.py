def _domain_of(address):
    """Extract the lowercase domain portion of an email address.

    Returns an empty string if the address has no domain part.
    """
    if not address or "@" not in address:
        return ""
    return address.rsplit("@", 1)[1].strip().lower().rstrip(".")


def _registrable_domain(domain):
    """Reduce a hostname to roughly its registrable domain.

    This is a simplification. Proper handling requires the Public Suffix List,
    because 'example.co.uk' has a two-part suffix while 'example.com' has one.
    We approximate by taking the last two labels, and note the inaccuracy here
    rather than pulling in another dependency for a course project.

        mail.paypal.com  -> paypal.com
        example.co.uk    -> co.uk        (WRONG, but consistently wrong)
    """
    parts = [p for p in domain.split(".") if p]
    if len(parts) <= 2:
        return domain
    return ".".join(parts[-2:])


def _levenshtein(a, b):
    """Compute Levenshtein edit distance between two strings.

    Implemented directly rather than pulled from a library so that the
    algorithm is visible and auditable in the source, and so the tool has one
    fewer dependency.

    Uses the standard two-row dynamic programming approach: O(len(a)*len(b))
    time, O(min(len(a), len(b))) space.
    """
    if a == b:
        return 0
    if not a:
        return len(b)
    if not b:
        return len(a)

    # Keep the shorter string as the inner loop to minimize row width.
    if len(a) > len(b):
        a, b = b, a

    previous_row = list(range(len(a) + 1))

    for i, char_b in enumerate(b, start=1):
        current_row = [i]
        for j, char_a in enumerate(a, start=1):
            insert_cost = current_row[j - 1] + 1
            delete_cost = previous_row[j] + 1
            replace_cost = previous_row[j - 1] + (0 if char_a == char_b else 1)
            current_row.append(min(insert_cost, delete_cost, replace_cost))
        previous_row = current_row

    return previous_row[-1]


