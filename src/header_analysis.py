def analyze_addresses(header_map):
    """Compare From, Reply-To, Return-Path, and display names for consistency.

    Returns:
        dict: Parsed address components plus a list of finding dictionaries.
    """
    findings = []

    from_display, from_address = parseaddr(header_map.get("from", ""))
    reply_display, reply_address = parseaddr(header_map.get("reply-to", ""))
    _, return_path = parseaddr(header_map.get("return-path", ""))
    _, sender_address = parseaddr(header_map.get("sender", ""))

    from_domain = _domain_of(from_address)
    reply_domain = _domain_of(reply_address)
    return_domain = _domain_of(return_path)

    # --- Check 1: Reply-To points to a different domain than From -----------
    # Legitimate bulk mail does sometimes do this, so on its own it is
    # suggestive rather than conclusive. Combined with an auth failure it is
    # a strong signal.
    if reply_address and from_address and reply_domain != from_domain:
        findings.append({
            "code": "REPLYTO_MISMATCH",
            "severity": "high",
            "title": "Reply-To domain differs from From domain",
            "detail": (
                f"Replies would be sent to '{reply_address}' "
                f"(domain: {reply_domain or 'none'}) rather than to the "
                f"apparent sender '{from_address}' (domain: "
                f"{from_domain or 'none'}). This is a common technique for "
                f"routing victim responses to an attacker-controlled mailbox."
            ),
        })

    # --- Check 2: Return-Path (bounce address) differs from From ------------
    # The envelope sender is what SPF actually validates against, so a mismatch
    # here explains how a message can pass SPF while still being spoofed.
    if return_path and from_address and return_domain != from_domain:
        findings.append({
            "code": "RETURNPATH_MISMATCH",
            "severity": "medium",
            "title": "Return-Path domain differs from From domain",
            "detail": (
                f"The envelope sender is '{return_path}' but the message "
                f"displays as being from '{from_address}'. SPF validates the "
                f"envelope sender, so a message can pass SPF for the "
                f"Return-Path domain while still displaying a spoofed From "
                f"address to the recipient."
            ),
        })

    # --- Check 3: Display name contains an address that isn't the real one --
    # Rendered as:  "security@paypal.com" <attacker@evil.ru>
    # Many mail clients show only the display name, so the victim sees the
    # legitimate-looking string and never the real address.
    display_addresses = re.findall(r"[\w\.\-\+]+@[\w\.\-]+\.\w+", from_display or "")
    for candidate in display_addresses:
        if candidate.lower() != (from_address or "").lower():
            findings.append({
                "code": "DISPLAY_NAME_ADDRESS_SPOOF",
                "severity": "high",
                "title": "Display name contains a different email address",
                "detail": (
                    f"The display name contains '{candidate}' but the actual "
                    f"sending address is '{from_address}'. Many mail clients "
                    f"show only the display name, so the recipient may never "
                    f"see the real address."
                ),
            })

    # --- Check 4: Corporate display name on a free-mail address -------------
    if from_domain in FREE_MAIL_PROVIDERS and from_display:
        lowered_display = from_display.lower()
        matched_terms = [t for t in CORPORATE_DISPLAY_TERMS if t in lowered_display]
        if matched_terms:
            findings.append({
                "code": "CORPORATE_NAME_FREE_MAIL",
                "severity": "high",
                "title": "Corporate-style display name on a free mail account",
                "detail": (
                    f"The display name '{from_display}' uses institutional "
                    f"language ({', '.join(matched_terms)}) but the message "
                    f"was sent from '{from_domain}', a free consumer mail "
                    f"provider. Organizations send official mail from their "
                    f"own domains."
                ),
            })

    # --- Check 5: No From header at all -------------------------------------
    if not from_address:
        findings.append({
            "code": "MISSING_FROM",
            "severity": "medium",
            "title": "No parseable From address",
            "detail": (
                "The message has no From header, or the header could not be "
                "parsed. Well-formed mail always carries a valid From address."
            ),
        })

    return {
        "from_display": from_display,
        "from_address": from_address,
        "from_domain": from_domain,
        "reply_to_address": reply_address,
        "reply_to_domain": reply_domain,
        "return_path": return_path,
        "return_path_domain": return_domain,
        "sender_address": sender_address,
        "to_addresses": [addr for _, addr in
                         getaddresses([header_map.get("to", "")]) if addr],
        "findings": findings,
    }


