def analyze_headers(parsed_email, audit_log=None):
    """Run the full header analysis pipeline.

    Args:
        parsed_email (dict): Output of email_parser.parse_email().
        audit_log (AuditLog | None): Optional audit log.

    Returns:
        dict: {
            "received_chain": [...],
            "authentication": {...},
            "addresses": {...},
            "subject": str,
            "date": str,
            "message_id": str,
            "findings": [...]     All findings from every check, combined.
        }
    """
    headers = parsed_email["headers"]
    header_map = parsed_email["header_map"]

    if audit_log:
        audit_log.record("HEADER_ANALYSIS_START", "Analyzing message headers")

    chain = parse_received_chain(headers)
    auth = parse_authentication(headers, header_map)
    addresses = analyze_addresses(header_map)

    findings = list(addresses["findings"])

    # --- Authentication failures -------------------------------------------
    # Treat only explicit failure verdicts as findings. A missing verdict means
    # the receiving server did not record one, which is not the same as a
    # failure and should not be reported as though it were.
    failure_verdicts = {"fail", "softfail", "permerror", "temperror", "none"}

    if auth["spf"] in failure_verdicts:
        findings.append({
            "code": f"SPF_{auth['spf'].upper()}",
            "severity": "high" if auth["spf"] == "fail" else "medium",
            "title": f"SPF check result: {auth['spf']}",
            "detail": (
                f"The receiving mail server recorded an SPF result of "
                f"'{auth['spf']}'. SPF verifies that the sending IP address is "
                f"authorized to send mail for the envelope sender's domain. A "
                f"result other than 'pass' means that authorization could not "
                f"be confirmed."
            ),
        })

    if auth["dkim"] in failure_verdicts:
        findings.append({
            "code": f"DKIM_{auth['dkim'].upper()}",
            "severity": "high" if auth["dkim"] == "fail" else "medium",
            "title": f"DKIM check result: {auth['dkim']}",
            "detail": (
                f"The receiving mail server recorded a DKIM result of "
                f"'{auth['dkim']}'. DKIM verifies a cryptographic signature "
                f"applied by the sending domain. A failure means the signature "
                f"was absent, invalid, or did not match the message content."
            ),
        })

    if auth["dmarc"] in failure_verdicts:
        findings.append({
            "code": f"DMARC_{auth['dmarc'].upper()}",
            "severity": "high" if auth["dmarc"] == "fail" else "medium",
            "title": f"DMARC check result: {auth['dmarc']}",
            "detail": (
                f"The receiving mail server recorded a DMARC result of "
                f"'{auth['dmarc']}'. DMARC ties SPF and DKIM results back to "
                f"the visible From domain. A DMARC failure means the message "
                f"did not authenticate as the domain it claims to be from."
            ),
        })

    # --- Lookalike domains --------------------------------------------------
    for domain_label, domain_value in (
        ("From", addresses["from_domain"]),
        ("Reply-To", addresses["reply_to_domain"]),
        ("Return-Path", addresses["return_path_domain"]),
    ):
        for finding in check_lookalike_domain(domain_value):
            finding = dict(finding)  # Copy so we don't mutate shared state.
            finding["title"] = f"{domain_label}: {finding['title']}"
            findings.append(finding)

    # --- Parse notes promoted to findings -----------------------------------
    for note in parsed_email.get("parse_notes", []):
        findings.append({
            "code": "PARSE_ANOMALY",
            "severity": "low",
            "title": "Message structure anomaly",
            "detail": note,
        })

    if audit_log:
        audit_log.record(
            "HEADER_ANALYSIS_COMPLETE",
            f"{len(chain)} hop(s) in Received chain, "
            f"SPF={auth['spf']}, DKIM={auth['dkim']}, DMARC={auth['dmarc']}, "
            f"{len(findings)} finding(s)",
        )

    return {
        "received_chain": chain,
        "authentication": auth,
        "addresses": addresses,
        "subject": header_map.get("subject", ""),
        "date": header_map.get("date", ""),
        "message_id": header_map.get("message-id", ""),
        "findings": findings,
    }
