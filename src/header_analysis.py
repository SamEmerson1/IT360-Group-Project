def check_lookalike_domain(domain):
    """Test whether a domain appears designed to impersonate a known brand.

    Returns:
        list[dict]: Findings. Empty if nothing suspicious was detected.

    Three separate techniques:
      1. Punycode (xn--) prefix, which allows visually identical Unicode
         characters to stand in for ASCII ones.
      2. Small edit distance from a commonly impersonated domain.
      3. A brand name appearing as a substring of a longer unrelated domain,
         e.g. paypal-account-verify.tk
    """
    findings = []
    if not domain:
        return findings

    domain = domain.lower()
    registrable = _registrable_domain(domain)

    # --- Punycode -----------------------------------------------------------
    if "xn--" in domain:
        findings.append({
            "code": "PUNYCODE_DOMAIN",
            "severity": "high",
            "title": "Domain uses punycode encoding",
            "detail": (
                f"The domain '{domain}' is punycode-encoded, meaning it "
                f"contains non-ASCII characters. Some Unicode characters are "
                f"visually indistinguishable from Latin letters, which allows "
                f"a domain to render as a legitimate brand while being an "
                f"entirely different registration."
            ),
        })

    for brand in COMMONLY_IMPERSONATED:
        if registrable == brand:
            continue  # Exact match -- this is the real domain.

        # --- Edit distance --------------------------------------------------
        # A threshold of 1-2 catches character substitution (paypa1.com),
        # omission (payal.com), and insertion (payypal.com), without producing
        # excessive false positives on genuinely unrelated short domains.
        distance = _levenshtein(registrable, brand)
        if 0 < distance <= 2 and abs(len(registrable) - len(brand)) <= 2:
            findings.append({
                "code": "LOOKALIKE_DOMAIN",
                "severity": "high",
                "title": f"Domain closely resembles {brand}",
                "detail": (
                    f"'{registrable}' differs from the legitimate domain "
                    f"'{brand}' by only {distance} character(s). This is "
                    f"consistent with a typosquatting or impersonation "
                    f"registration."
                ),
            })
            continue

        # --- Brand as substring of a different domain -----------------------
        brand_name = brand.split(".")[0]
        if len(brand_name) >= 5 and brand_name in domain and registrable != brand:
            findings.append({
                "code": "BRAND_IN_UNRELATED_DOMAIN",
                "severity": "medium",
                "title": f"Domain contains the brand name '{brand_name}'",
                "detail": (
                    f"The domain '{domain}' contains '{brand_name}' but is not "
                    f"registered under '{brand}'. Attackers commonly build "
                    f"domains such as '{brand_name}-security-alert.example' to "
                    f"appear affiliated with a brand they do not control."
                ),
            })

    return findings


