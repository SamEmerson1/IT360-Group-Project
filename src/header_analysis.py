def parse_received_chain(headers):
    """Reconstruct the message's delivery path from its Received headers.

    Args:
        headers (list): [(name, value), ...] in original order.

    Returns:
        list[dict]: One entry per hop, ordered OLDEST FIRST (that is, reversed
            from how they appear in the message), each containing:
                hop_number, from_host, by_host, protocol, ip, timestamp, raw

    Reading oldest-first matches how a human reconstructs a route: start at the
    origin and follow it forward to the recipient.
    """
    received_values = [value for name, value in headers
                       if name.lower() == "received"]

    # Received headers appear newest-first in the raw message, so reversing
    # gives us chronological order.
    received_values = list(reversed(received_values))

    chain = []
    for index, raw in enumerate(received_values, start=1):
        # Collapse the folded whitespace that multi-line headers contain, so
        # our regexes see one continuous string.
        flat = " ".join(raw.split())

        from_match = _RECEIVED_FROM.search(flat)
        by_match = _RECEIVED_BY.search(flat)
        with_match = _RECEIVED_WITH.search(flat)
        ip_match = _RECEIVED_IP.search(flat)
        date_match = _RECEIVED_DATE.search(flat)

        chain.append({
            "hop_number": index,
            "from_host": from_match.group(1) if from_match else None,
            "by_host": by_match.group(1) if by_match else None,
            "protocol": with_match.group(1) if with_match else None,
            "ip": ip_match.group(1) if ip_match else None,
            "timestamp": date_match.group(1).strip() if date_match else None,
            "raw": flat,
        })

    return chain


