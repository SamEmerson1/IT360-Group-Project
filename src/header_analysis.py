def parse_authentication(headers, header_map):
    """Extract SPF, DKIM, and DMARC verdicts recorded by receiving servers.

    Returns:
        dict: {
            "spf": str | None,      e.g. "pass", "fail", "softfail", "none"
            "dkim": str | None,
            "dmarc": str | None,
            "compauth": str | None,  Microsoft composite authentication
            "sources": list[str],    raw headers the verdicts came from
        }

    We scan every Authentication-Results header (a message may carry several,
    one per hop) as well as the older Received-SPF header. Where multiple hops
    disagree, we keep the FIRST verdict encountered when reading the headers in
    message order -- that is the one written by the server closest to the
    recipient, which is the one we trust most.
    """
    results = {
        "spf": None, "dkim": None, "dmarc": None,
        "compauth": None, "sources": [],
    }

    for name, value in headers:
        lowered = name.lower()
        if lowered not in ("authentication-results", "received-spf",
                           "arc-authentication-results",
                           "x-forefront-antispam-report"):
            continue

        flat = " ".join(value.split())
        results["sources"].append(f"{name}: {flat}")

        for method, verdict in _AUTH_METHOD.findall(flat):
            key = method.lower()
            if key in results and results[key] is None:
                results[key] = verdict.lower()

    # Received-SPF sometimes states its verdict as the first word of the header
    # rather than in "spf=" form.
    if results["spf"] is None and "received-spf" in header_map:
        first_word = header_map["received-spf"].strip().split()
        if first_word:
            results["spf"] = first_word[0].lower().rstrip(":,;")

    return results


