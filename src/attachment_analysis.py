def identify_by_magic(data):
    """Identify a file's real format from its leading bytes.

    Args:
        data (bytes): The file contents (only the first bytes are examined).

    Returns:
        str | None: Human-readable format name, or None if unrecognized.
    """
    if not data:
        return None

    # Check longest signatures first so that, for example, the 8-byte PNG
    # signature is preferred over any shorter prefix it might share.
    for signature in sorted(MAGIC_SIGNATURES, key=len, reverse=True):
        if data.startswith(signature):
            return MAGIC_SIGNATURES[signature]

    return None


def _split_extensions(filename):
    """Return all extension-like suffixes of a filename, in order.

        "invoice.pdf.exe" -> [".pdf", ".exe"]
        "report.docx"     -> [".docx"]
        "archive"         -> []

    Only suffixes that look like real extensions (1-5 alphanumeric characters)
    are returned, so version numbers such as "backup.2024.zip" do not produce
    a spurious ".2024" entry.
    """
    parts = filename.split(".")
    if len(parts) < 2:
        return []

    extensions = []
    for part in parts[1:]:
        if 1 <= len(part) <= 5 and part.isalnum():
            extensions.append("." + part.lower())
    return extensions


