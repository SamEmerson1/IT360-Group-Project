def evaluate_attachment(attachment):
    """Analyze a single attachment.

    Args:
        attachment (dict): {filename, declared_type, data} from email_parser.

    Returns:
        dict: Attachment metadata, hashes, and findings. The raw `data` is
            deliberately NOT included in the return value, so that the report
            layer cannot accidentally serialize malware into a JSON file.
    """
    filename = attachment.get("filename") or "(unnamed)"
    declared_type = attachment.get("declared_type", "unknown")
    data = attachment.get("data") or b""

    findings = []

    hashes = hash_bytes(data)
    actual_type = identify_by_magic(data)
    extensions = _split_extensions(filename)
    final_extension = extensions[-1] if extensions else ""

    # --- Check 1: Bidirectional control characters in the filename ----------
    for char, name in BIDI_CONTROL_CHARS.items():
        if char in filename:
            # Show the filename with the control character made visible, since
            # printing it raw would reproduce the very deception we're
            # reporting on.
            safe_display = filename.replace(char, f"<{name}>")
            findings.append({
                "code": "BIDI_FILENAME_SPOOF",
                "severity": "high",
                "title": "Filename contains a Unicode direction-override character",
                "detail": (
                    f"The filename contains U+{ord(char):04X} ({name}), which "
                    f"reverses how the following text is displayed. The name "
                    f"renders differently than it is actually stored. With the "
                    f"control character made visible, the true name is: "
                    f"{safe_display}"
                ),
            })

    # --- Check 2: Dangerous extension ---------------------------------------
    if final_extension in DANGEROUS_EXTENSIONS:
        severity = DANGEROUS_EXTENSIONS[final_extension]
        findings.append({
            "code": "DANGEROUS_EXTENSION",
            "severity": severity,
            "title": f"Attachment has an executable or scriptable extension "
                     f"({final_extension})",
            "detail": (
                f"'{filename}' uses the {final_extension} extension, which can "
                f"execute code when opened. Attachments of this type in "
                f"unsolicited mail should be treated as hostile until proven "
                f"otherwise."
            ),
        })

    # --- Check 3: Double extension ------------------------------------------
    if len(extensions) >= 2:
        # Only interesting when the first extension looks like a document type
        # and the last one is executable -- the classic disguise pattern.
        first = extensions[-2]
        if first in EXPECTED_TYPE_BY_EXTENSION and final_extension in DANGEROUS_EXTENSIONS:
            findings.append({
                "code": "DOUBLE_EXTENSION",
                "severity": "high",
                "title": "Filename uses a double extension",
                "detail": (
                    f"'{filename}' ends in {final_extension} but has "
                    f"{first} before it. Windows hides known extensions by "
                    f"default, so the recipient may see only the "
                    f"'{filename.rsplit('.', 1)[0]}' portion and believe the "
                    f"file is a {first.lstrip('.').upper()} document."
                ),
            })

    # --- Check 4: Magic bytes contradict the declared extension -------------
    if actual_type and final_extension in EXPECTED_TYPE_BY_EXTENSION:
        expected = EXPECTED_TYPE_BY_EXTENSION[final_extension]
        if actual_type not in expected:
            findings.append({
                "code": "FILE_TYPE_MISMATCH",
                "severity": "high",
                "title": "File content does not match its extension",
                "detail": (
                    f"'{filename}' claims to be a {final_extension} file, but "
                    f"its magic bytes identify it as: {actual_type}. The file "
                    f"has been renamed to disguise what it actually is."
                ),
            })

    # --- Check 5: Unrecognized content with an executable extension ---------
    if actual_type is None and data and final_extension in DANGEROUS_EXTENSIONS:
        findings.append({
            "code": "UNKNOWN_BINARY_CONTENT",
            "severity": "medium",
            "title": "Attachment content could not be identified",
            "detail": (
                f"The leading bytes of '{filename}' do not match any known "
                f"file signature. Combined with its extension, this warrants "
                f"analysis in an isolated environment."
            ),
        })

    # --- Check 6: Archive format --------------------------------------------
    if final_extension in ARCHIVE_EXTENSIONS:
        findings.append({
            "code": "ARCHIVE_ATTACHMENT",
            "severity": "low",
            "title": f"Attachment is an archive ({final_extension})",
            "detail": (
                f"'{filename}' is a compressed archive. Archives conceal their "
                f"contents from mail-gateway scanning, and password-protected "
                f"archives with the password supplied in the message body are "
                f"a well-established malware delivery technique. This tool "
                f"does not extract archives; examine the contents in an "
                f"isolated environment."
            ),
        })

    # --- Check 7: Declared MIME type contradicts actual content -------------
    # A message claiming an attachment is a PDF while the bytes say otherwise
    # is trying to get past filters that trust the Content-Type header.
    if actual_type and declared_type:
        mime_hints = {
            "application/pdf": "PDF document",
            "image/jpeg": "JPEG image",
            "image/png": "PNG image",
            "image/gif": "GIF image",
        }
        expected_from_mime = mime_hints.get(declared_type.lower())
        if expected_from_mime and expected_from_mime != actual_type:
            findings.append({
                "code": "MIME_TYPE_MISMATCH",
                "severity": "medium",
                "title": "Declared MIME type does not match file content",
                "detail": (
                    f"The message declares '{filename}' as {declared_type}, "
                    f"but its content is actually: {actual_type}."
                ),
            })

    # --- Check 8: Empty attachment ------------------------------------------
    if not data:
        findings.append({
            "code": "EMPTY_ATTACHMENT",
            "severity": "low",
            "title": "Attachment is empty",
            "detail": (
                f"'{filename}' contains no data. This may indicate a truncated "
                f"message, a decoding failure, or a deliberately malformed "
                f"attachment intended to confuse scanning tools."
            ),
        })

    return {
        "filename": filename,
        "declared_type": declared_type,
        "actual_type": actual_type or "unidentified",
        "extension": final_extension,
        "all_extensions": extensions,
        "size_bytes": hashes["size_bytes"],
        "md5": hashes["md5"],
        "sha256": hashes["sha256"],
        "findings": findings,
    }


def analyze_attachments(parsed_email, audit_log=None):
    """Run the full attachment analysis pipeline.

    Returns:
        dict: {
            "attachments": [...],
            "findings": [...],
        }
    """
    if audit_log:
        audit_log.record(
            "ATTACHMENT_ANALYSIS_START",
            f"Analyzing {len(parsed_email['attachments'])} attachment(s)",
        )

    results = []
    all_findings = []

    for attachment in parsed_email["attachments"]:
        result = evaluate_attachment(attachment)
        results.append(result)
        all_findings.extend(result["findings"])

        if audit_log:
            audit_log.record(
                "ATTACHMENT_HASHED",
                f"{result['filename']} -- SHA-256: {result['sha256']} "
                f"({result['size_bytes']} bytes, type: {result['actual_type']})",
            )

    if audit_log:
        audit_log.record(
            "ATTACHMENT_ANALYSIS_COMPLETE",
            f"{len(results)} attachment(s), {len(all_findings)} finding(s)",
        )

    return {"attachments": results, "findings": all_findings}
