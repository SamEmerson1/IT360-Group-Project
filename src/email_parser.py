import os
from email import policy
from email.parser import BytesParser
from email.header import decode_header, make_header

# `extract_msg` is an optional dependency. We probe for it at import time so
# that the rest of the module can check a simple boolean instead of wrapping
# every call site in its own try/except.
try:
    import extract_msg  # type: ignore
    _HAS_EXTRACT_MSG = True
except ImportError:
    _HAS_EXTRACT_MSG = False


class EmailParseError(Exception):
    """Raised when an email file cannot be parsed at all.

    This is reserved for genuinely unrecoverable situations -- the file is not
    an email, or it is so damaged that no headers can be read. Partial or
    slightly malformed messages should be parsed as best we can rather than
    raising.
    """
    pass


def _decode_header_value(raw):
    """Decode an RFC 2047 encoded header into readable text.

    Mail headers must be ASCII on the wire, so non-ASCII content is encoded
    like:  =?UTF-8?B?SGVsbG8gV29ybGQ=?=

    This matters for phishing analysis specifically, because attackers use
    encoded headers to hide suspicious display names from tools that only do
    naive substring matching on the raw header text.

    Args:
        raw (str | None): The raw header value.

    Returns:
        str: Decoded text, or an empty string if the value was absent.
    """
    if raw is None:
        return ""
    try:
        return str(make_header(decode_header(raw)))
    except Exception:
        # Malformed encoded-words are common in spam and phishing. Falling back
        # to the raw string is better than losing the header entirely.
        return str(raw)


def _get_all_headers(message):
    """Return every header as a list of (name, decoded_value) tuples.

    We preserve order and duplicates. Order matters enormously for `Received:`
    headers, which form a stack: the newest hop is at the top. Duplicates
    matter because the presence of two `From:` headers is itself a red flag,
    since different mail clients may display different ones.
    """
    headers = []
    for name, value in message.items():
        headers.append((name, _decode_header_value(value)))
    return headers


def _extract_bodies(message):
    """Pull the plain-text and HTML bodies out of a message.

    Returns:
        dict: {"text": str | None, "html": str | None}

    A phishing message will very often have a benign-looking plain-text part
    and a deceptive HTML part, because some filters only inspect the former.
    We therefore keep both and analyze both.
    """
    bodies = {"text": None, "html": None}

    if message.is_multipart():
        for part in message.walk():
            # Skip container parts and anything marked as an attachment.
            if part.get_content_maintype() == "multipart":
                continue
            if part.get_content_disposition() == "attachment":
                continue

            content_type = part.get_content_type()
            try:
                payload = part.get_content()
            except Exception:
                # Fall back to raw decoding if the declared charset is invalid,
                # which is very common in phishing mail.
                raw = part.get_payload(decode=True)
                if raw is None:
                    continue
                payload = raw.decode("utf-8", errors="replace")

            if content_type == "text/plain" and bodies["text"] is None:
                bodies["text"] = payload
            elif content_type == "text/html" and bodies["html"] is None:
                bodies["html"] = payload
    else:
        # Single-part message.
        try:
            payload = message.get_content()
        except Exception:
            raw = message.get_payload(decode=True)
            payload = raw.decode("utf-8", errors="replace") if raw else ""

        if message.get_content_type() == "text/html":
            bodies["html"] = payload
        else:
            bodies["text"] = payload

    return bodies


def _extract_attachments(message):
    """Extract attachment metadata and raw bytes.

    Returns:
        list[dict]: One entry per attachment, each containing:
            filename            -- as declared in the message
            declared_type       -- MIME type the message claims
            data                -- raw bytes of the attachment

    IMPORTANT: attachments are held in memory and never written to disk by this
    tool. Some of them are live malware, and silently dropping executables into
    an analyst's working directory would be irresponsible. Hashing happens
    in memory in attachment_analysis.py.
    """
    attachments = []

    if not message.is_multipart():
        return attachments

    for part in message.walk():
        if part.get_content_maintype() == "multipart":
            continue

        disposition = part.get_content_disposition()
        filename = part.get_filename()

        # An attachment is either explicitly marked as one, or is a non-text
        # part that carries a filename. The second case catches messages that
        # omit Content-Disposition, which malformed phishing mail often does.
        is_attachment = disposition == "attachment" or (
            filename is not None and disposition != "inline"
        )
        if not is_attachment:
            continue

        try:
            data = part.get_payload(decode=True) or b""
        except Exception:
            data = b""

        attachments.append({
            "filename": _decode_header_value(filename) if filename else "(unnamed)",
            "declared_type": part.get_content_type(),
            "data": data,
        })

    return attachments


def _parse_eml(path):
    """Parse an RFC 5322 .eml file."""
    # policy.default gives us the modern email API with proper header decoding
    # and structured address parsing. The legacy compat32 policy is much harder
    # to work with and mishandles internationalized headers.
    with open(path, "rb") as handle:
        message = BytesParser(policy=policy.default).parse(handle)

    if not message.items():
        raise EmailParseError(
            f"No headers found in {path}. File may not be an email message."
        )

    return message


def _parse_msg(path):
    """Parse an Outlook .msg file into an RFC 5322 message object.

    Strategy: use `extract_msg` to read the OLE2 container, then ask it for an
    RFC 5322 representation so the rest of our pipeline can treat it exactly
    like an .eml. This avoids maintaining two parallel analysis paths.
    """
    if not _HAS_EXTRACT_MSG:
        raise EmailParseError(
            "Cannot parse .msg files: the 'extract_msg' library is not "
            "installed. Install it with 'pip install extract-msg', or convert "
            "the message to .eml first."
        )

    msg = extract_msg.Message(path)
    try:
        # as_email() hands back a standard email.message.Message object.
        return msg.as_email()
    finally:
        msg.close()


def parse_email(path, audit_log=None):
    """Parse an email file into the normalized structure used tool-wide.

    Args:
        path (str): Path to a .eml or .msg file.
        audit_log (AuditLog | None): If provided, parsing steps are recorded.

    Returns:
        dict with keys:
            source_path   (str)   Original file path
            format        (str)   "eml" or "msg"
            headers       (list)  [(name, value), ...] in original order
            header_map    (dict)  Lowercased name -> first value, for lookups
            bodies        (dict)  {"text": ..., "html": ...}
            attachments   (list)  [{filename, declared_type, data}, ...]
            parse_notes   (list)  Non-fatal problems encountered

    Raises:
        EmailParseError: If the file cannot be parsed at all.
        FileNotFoundError: If the path does not exist.
    """
    if not os.path.isfile(path):
        raise FileNotFoundError(f"Evidence file not found: {path}")

    extension = os.path.splitext(path)[1].lower()
    parse_notes = []

    if audit_log:
        audit_log.record("PARSE_START", f"Parsing {path} (format: {extension})")

    if extension == ".msg":
        message = _parse_msg(path)
        fmt = "msg"
    else:
        # Anything that is not explicitly .msg gets treated as RFC 5322. This
        # is intentional -- users regularly rename evidence to .txt or drop the
        # extension entirely, and the format is self-describing enough that
        # attempting the parse is more useful than refusing on extension alone.
        if extension not in (".eml", ".txt", ""):
            parse_notes.append(
                f"Unexpected extension '{extension}'; attempting RFC 5322 parse."
            )
        message = _parse_eml(path)
        fmt = "eml"

    headers = _get_all_headers(message)

    # Build a convenience lookup map. Header names are case-insensitive per
    # RFC 5322, so we normalize to lowercase. Where a header appears more than
    # once we keep the FIRST occurrence here, and note the duplication --
    # duplicate From/Subject headers are a known spoofing technique.
    header_map = {}
    seen_counts = {}
    for name, value in headers:
        key = name.lower()
        seen_counts[key] = seen_counts.get(key, 0) + 1
        if key not in header_map:
            header_map[key] = value

    for key, count in seen_counts.items():
        if count > 1 and key in ("from", "subject", "to", "reply-to", "date"):
            parse_notes.append(
                f"Header '{key}' appears {count} times. Duplicate headers of "
                f"this type can be used to make different mail clients display "
                f"different values."
            )

    bodies = _extract_bodies(message)
    attachments = _extract_attachments(message)

    if audit_log:
        audit_log.record(
            "PARSE_COMPLETE",
            f"{len(headers)} headers, "
            f"{len(attachments)} attachment(s), "
            f"text_body={'yes' if bodies['text'] else 'no'}, "
            f"html_body={'yes' if bodies['html'] else 'no'}",
        )
        for note in parse_notes:
            audit_log.record("PARSE_NOTE", note)

    return {
        "source_path": path,
        "format": fmt,
        "headers": headers,
        "header_map": header_map,
        "bodies": bodies,
        "attachments": attachments,
        "parse_notes": parse_notes,
    }
