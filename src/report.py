def write_ioc_csv(analysis, path):
    """Write extracted indicators of compromise as CSV.

    Columns: type, value, defanged_value, context, source

    This is the file an analyst feeds into a blocklist, a SIEM watchlist, or a
    threat intelligence platform. Both raw and defanged values are included:
    the raw value is what a machine needs, the defanged value is what a human
    can safely read.
    """
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)

    rows = []
    headers = analysis["headers"]
    addresses = headers["addresses"]

    # --- Sender addresses ---------------------------------------------------
    if addresses["from_address"]:
        rows.append({
            "type": "email_address",
            "value": addresses["from_address"],
            "defanged_value": addresses["from_address"].replace("@", "[@]").replace(".", "[.]"),
            "context": "From header",
            "source": "header",
        })
    if addresses["reply_to_address"]:
        rows.append({
            "type": "email_address",
            "value": addresses["reply_to_address"],
            "defanged_value": addresses["reply_to_address"].replace("@", "[@]").replace(".", "[.]"),
            "context": "Reply-To header",
            "source": "header",
        })
    if addresses["return_path"]:
        rows.append({
            "type": "email_address",
            "value": addresses["return_path"],
            "defanged_value": addresses["return_path"].replace("@", "[@]").replace(".", "[.]"),
            "context": "Return-Path header",
            "source": "header",
        })

    # --- Originating IP addresses -------------------------------------------
    for hop in headers["received_chain"]:
        if hop["ip"]:
            rows.append({
                "type": "ipv4",
                "value": hop["ip"],
                "defanged_value": hop["ip"].replace(".", "[.]"),
                "context": f"Received hop {hop['hop_number']} "
                           f"(from {hop['from_host'] or 'unknown'})",
                "source": "header",
            })

    # --- URLs ---------------------------------------------------------------
    for entry in analysis["urls"]["urls"]:
        rows.append({
            "type": "url",
            "value": entry["url"],
            "defanged_value": entry["defanged"],
            "context": f"{len(entry['findings'])} finding(s); "
                       f"link text: {entry['anchor_text'] or 'none'}",
            "source": entry["source"],
        })

    # --- Attachment hashes --------------------------------------------------
    for item in analysis["attachments"]["attachments"]:
        rows.append({
            "type": "sha256",
            "value": item["sha256"],
            "defanged_value": item["sha256"],  # Hashes need no defanging.
            "context": f"Attachment: {item['filename']} ({item['actual_type']})",
            "source": "attachment",
        })
        rows.append({
            "type": "md5",
            "value": item["md5"],
            "defanged_value": item["md5"],
            "context": f"Attachment: {item['filename']} ({item['actual_type']})",
            "source": "attachment",
        })

    with open(path, "w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(
            handle,
            fieldnames=["type", "value", "defanged_value", "context", "source"],
        )
        writer.writeheader()
        writer.writerows(rows)

    return path, len(rows)


