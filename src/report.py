def print_console_report(analysis, use_color=True):
    """Print a human-readable summary to stdout."""
    risk = analysis["risk"]
    headers = analysis["headers"]
    addresses = headers["addresses"]
    integrity = analysis["integrity"]

    band_color = _BAND_COLORS.get(risk["band"], "cyan")
    line = "=" * 72

    print()
    print(_c(line, "dim", use_color))
    print(_c("  PHISHING EMAIL FORENSICS ANALYZER", "bold", use_color))
    print(_c("  IT 360 Final Project -- Tyler and Sam", "dim", use_color))
    print(_c(line, "dim", use_color))
    print()

    # --- Verdict ------------------------------------------------------------
    print(f"  {_c('VERDICT:', 'bold', use_color)} "
          f"{_c(risk['band'], band_color, use_color)}  "
          f"(risk score {risk['score']}/100)")
    print(f"  {risk['guidance']}")
    print()

    # --- Evidence identification -------------------------------------------
    print(_c("  EVIDENCE", "bold", use_color))
    print(f"    File:        {analysis['evidence']['path']}")
    print(f"    Size:        {analysis['evidence']['hashes_before']['size_bytes']} bytes")
    print(f"    MD5:         {analysis['evidence']['hashes_before']['md5']}")
    print(f"    SHA-256:     {analysis['evidence']['hashes_before']['sha256']}")
    integrity_color = "green" if integrity["verified"] else "red"
    print(f"    Integrity:   {_c(integrity['message'], integrity_color, use_color)}")
    print()

    # --- Message summary ----------------------------------------------------
    print(_c("  MESSAGE", "bold", use_color))
    print(f"    Subject:     {headers['subject'] or '(none)'}")
    print(f"    From:        {addresses['from_display'] or '(no display name)'} "
          f"<{addresses['from_address'] or 'unknown'}>")
    if addresses["reply_to_address"]:
        print(f"    Reply-To:    {addresses['reply_to_address']}")
    if addresses["return_path"]:
        print(f"    Return-Path: {addresses['return_path']}")
    print(f"    Date:        {headers['date'] or '(none)'}")
    print(f"    Message-ID:  {headers['message_id'] or '(none)'}")
    print()

    # --- Authentication -----------------------------------------------------
    auth = headers["authentication"]
    print(_c("  AUTHENTICATION", "bold", use_color))
    for method in ("spf", "dkim", "dmarc"):
        verdict = auth.get(method)
        if verdict is None:
            display = _c("not recorded", "dim", use_color)
        elif verdict == "pass":
            display = _c("pass", "green", use_color)
        else:
            display = _c(verdict, "red", use_color)
        print(f"    {method.upper():<6} {display}")
    print()

    # --- Delivery path ------------------------------------------------------
    chain = headers["received_chain"]
    print(_c(f"  DELIVERY PATH ({len(chain)} hop(s), oldest first)", "bold", use_color))
    if not chain:
        print(_c("    No Received headers found.", "dim", use_color))
    for hop in chain:
        origin = hop["from_host"] or "unknown"
        destination = hop["by_host"] or "unknown"
        ip_part = f" [{hop['ip']}]" if hop["ip"] else ""
        print(f"    {hop['hop_number']}. {origin}{ip_part}")
        print(f"       -> {destination}")
        if hop["timestamp"]:
            print(_c(f"       {hop['timestamp']}", "dim", use_color))
    print()

    # --- Findings -----------------------------------------------------------
    findings = _sorted_findings(analysis["all_findings"])
    print(_c(f"  FINDINGS ({len(findings)})", "bold", use_color))
    if not findings:
        print(_c("    No indicators detected.", "green", use_color))
    for finding in findings:
        severity = finding.get("severity", "low")
        color = {"high": "red", "medium": "yellow", "low": "cyan"}.get(severity, "cyan")
        print(f"    [{_c(severity.upper(), color, use_color)}] {finding['title']}")
        # Wrap the detail text at a readable width.
        detail = finding.get("detail", "")
        words = detail.split()
        current = "       "
        for word in words:
            if len(current) + len(word) + 1 > 72:
                print(_c(current, "dim", use_color))
                current = "       " + word
            else:
                current += (" " if current.strip() else "") + word
        if current.strip():
            print(_c(current, "dim", use_color))
        print()

    # --- URLs ---------------------------------------------------------------
    urls = analysis["urls"]["urls"]
    print(_c(f"  URLS ({len(urls)})", "bold", use_color))
    if not urls:
        print(_c("    None found.", "dim", use_color))
    for entry in urls:
        marker = _c("!", "red", use_color) if entry["findings"] else " "
        print(f"    {marker} {entry['defanged']}")
        if entry["anchor_text"]:
            print(_c(f"      link text: \"{entry['anchor_text']}\"", "dim", use_color))
        if entry["wrapper"]:
            print(_c(f"      unwrapped from: {entry['wrapper']}", "dim", use_color))
    print()

    # --- Attachments --------------------------------------------------------
    attachments = analysis["attachments"]["attachments"]
    print(_c(f"  ATTACHMENTS ({len(attachments)})", "bold", use_color))
    if not attachments:
        print(_c("    None found.", "dim", use_color))
    for item in attachments:
        marker = _c("!", "red", use_color) if item["findings"] else " "
        print(f"    {marker} {item['filename']}  ({item['size_bytes']} bytes)")
        print(_c(f"      declared: {item['declared_type']}", "dim", use_color))
        print(_c(f"      actual:   {item['actual_type']}", "dim", use_color))
        print(_c(f"      SHA-256:  {item['sha256']}", "dim", use_color))
    print()

    # --- AI summary ---------------------------------------------------------
    ai = analysis.get("ai_summary", {})
    print(_c("  AI-GENERATED SUMMARY", "bold", use_color))
    if ai.get("available"):
        print(_c(f"    Generated by {ai['model']}. Advisory only -- the "
                 f"findings and score above were produced by rule, not by "
                 f"the model.", "dim", use_color))
        print()
        for text_line in ai["text"].splitlines():
            print(f"    {text_line}")
    else:
        print(_c(f"    Not available. {ai.get('error', 'Unknown reason.')}",
                 "dim", use_color))
    print()
    print(_c(line, "dim", use_color))
    print()


