# Console formatting. ANSI codes are stripped when output is not a terminal,
# so redirecting to a file produces clean text.
_COLORS = {
    "reset": "\033[0m",
    "bold": "\033[1m",
    "dim": "\033[2m",
    "red": "\033[31m",
    "yellow": "\033[33m",
    "green": "\033[32m",
    "cyan": "\033[36m",
}

_BAND_COLORS = {
    "MALICIOUS": "red",
    "SUSPICIOUS": "yellow",
    "QUESTIONABLE": "yellow",
    "LOW RISK": "green",
}

_SEVERITY_ORDER = {"high": 0, "medium": 1, "low": 2}


def _c(text, color, enabled=True):
    """Wrap text in an ANSI color code when coloring is enabled."""
    if not enabled or color not in _COLORS:
        return text
    return f"{_COLORS[color]}{text}{_COLORS['reset']}"


def _sorted_findings(findings):
    """Sort findings by severity, most serious first."""
    return sorted(
        findings,
        key=lambda f: _SEVERITY_ORDER.get(f.get("severity", "low"), 3),
    )


