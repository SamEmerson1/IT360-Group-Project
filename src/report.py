def write_json_report(analysis, path):
    """Write the complete analysis as JSON.

    Everything in the analysis dictionary is JSON-serializable by construction:
    attachment binary data is dropped in attachment_analysis.py before it ever
    reaches this layer.
    """
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    with open(path, "w", encoding="utf-8") as handle:
        json.dump(analysis, handle, indent=2, default=str)
    return path


