def write_html_report(analysis, path):
    """Write a readable HTML report.

    Every interpolated value passes through html.escape(). Message content is
    attacker-controlled, and an unescaped filename or subject line would let an
    attacker inject script into a report that an analyst opens in a browser.
    """
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)

    def esc(value):
        return html.escape(str(value if value is not None else ""))

    risk = analysis["risk"]
    headers = analysis["headers"]
    addresses = headers["addresses"]
    auth = headers["authentication"]
    evidence = analysis["evidence"]

    # --- Delivery path ------------------------------------------------------
    chain = headers["received_chain"]
    if chain:
        rows = ["<table><tr><th>#</th><th>From</th><th>To</th>"
                "<th>IP</th><th>Timestamp</th></tr>"]
        for hop in chain:
            rows.append(
                f"<tr><td>{hop['hop_number']}</td>"
                f"<td><code>{esc(hop['from_host'] or '-')}</code></td>"
                f"<td><code>{esc(hop['by_host'] or '-')}</code></td>"
                f"<td><code>{esc(hop['ip'] or '-')}</code></td>"
                f"<td class='meta'>{esc(hop['timestamp'] or '-')}</td></tr>"
            )
        rows.append("</table>")
        delivery_rows = "\n".join(rows)
    else:
        delivery_rows = "<p class='meta'>No Received headers found.</p>"

    # --- Findings -----------------------------------------------------------
    findings = _sorted_findings(analysis["all_findings"])
    if findings:
        blocks = []
        for finding in findings:
            severity = esc(finding.get("severity", "low"))
            blocks.append(
                f"<div class='finding {severity}'>"
                f"<div class='sev'>{severity}</div>"
                f"<div class='title'>{esc(finding.get('title'))}</div>"
                f"<div class='detail'>{esc(finding.get('detail'))}</div>"
                f"</div>"
            )
        findings_html = "\n".join(blocks)
    else:
        findings_html = ("<p>No indicators detected. Note that this is not "
                         "proof of legitimacy.</p>")

    # --- URLs ---------------------------------------------------------------
    urls = analysis["urls"]["urls"]
    if urls:
        rows = ["<table><tr><th>URL (defanged)</th><th>Link text</th>"
                "<th>Source</th><th>Findings</th></tr>"]
        for entry in urls:
            wrapper_note = (f"<br><span class='meta'>unwrapped from "
                            f"{esc(entry['wrapper'])}</span>"
                            if entry["wrapper"] else "")
            rows.append(
                f"<tr><td><code>{esc(entry['defanged'])}</code>{wrapper_note}</td>"
                f"<td>{esc(entry['anchor_text'] or '-')}</td>"
                f"<td class='meta'>{esc(entry['source'])}</td>"
                f"<td>{len(entry['findings'])}</td></tr>"
            )
        rows.append("</table>")
        urls_html = "\n".join(rows)
    else:
        urls_html = "<p class='meta'>No URLs found.</p>"

    # --- Attachments --------------------------------------------------------
    attachments = analysis["attachments"]["attachments"]
    if attachments:
        rows = ["<table><tr><th>Filename</th><th>Declared</th><th>Actual</th>"
                "<th>Size</th><th>SHA-256</th></tr>"]
        for item in attachments:
            rows.append(
                f"<tr><td>{esc(item['filename'])}</td>"
                f"<td class='meta'>{esc(item['declared_type'])}</td>"
                f"<td>{esc(item['actual_type'])}</td>"
                f"<td>{item['size_bytes']}</td>"
                f"<td><code>{esc(item['sha256'])}</code></td></tr>"
            )
        rows.append("</table>")
        attachments_html = "\n".join(rows)
    else:
        attachments_html = "<p class='meta'>No attachments found.</p>"

    # --- AI summary ---------------------------------------------------------
    ai = analysis.get("ai_summary", {})
    if ai.get("available"):
        ai_html = (
            f"<p class='disclaimer'>Generated by {esc(ai['model'])}. This text "
            f"is advisory only. The findings and risk score above were produced "
            f"by deterministic rules and were not influenced by the model.</p>"
            f"<div class='ai'>{esc(ai['text'])}</div>"
        )
    else:
        ai_html = (f"<p class='meta'>Not available. "
                   f"{esc(ai.get('error', 'Unknown reason.'))}</p>")

    band_class = risk["band"].replace(" ", "")

    document = _HTML_TEMPLATE.format(
        generated_at=esc(analysis["generated_at"]),
        band=esc(risk["band"]),
        band_class=esc(band_class),
        score=risk["score"],
        guidance=esc(risk["guidance"]),
        evidence_path=esc(evidence["path"]),
        evidence_size=evidence["hashes_before"]["size_bytes"],
        evidence_md5=esc(evidence["hashes_before"]["md5"]),
        evidence_sha256=esc(evidence["hashes_before"]["sha256"]),
        integrity=esc(analysis["integrity"]["message"]),
        subject=esc(headers["subject"] or "(none)"),
        from_display=esc(addresses["from_display"] or "(no display name)"),
        from_address=esc(addresses["from_address"] or "unknown"),
        reply_to=esc(addresses["reply_to_address"] or "-"),
        return_path=esc(addresses["return_path"] or "-"),
        date=esc(headers["date"] or "-"),
        message_id=esc(headers["message_id"] or "-"),
        spf=esc(auth.get("spf") or "not recorded"),
        dkim=esc(auth.get("dkim") or "not recorded"),
        dmarc=esc(auth.get("dmarc") or "not recorded"),
        delivery_rows=delivery_rows,
        finding_count=len(findings),
        findings_html=findings_html,
        url_count=len(urls),
        urls_html=urls_html,
        attachment_count=len(attachments),
        attachments_html=attachments_html,
        ai_html=ai_html,
    )

    with open(path, "w", encoding="utf-8") as handle:
        handle.write(document)

    return path
