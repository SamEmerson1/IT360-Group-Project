"""
scoring.py -- Deterministic risk scoring from collected findings.

PURPOSE
    Turn a list of findings into a single, reproducible risk assessment.

WHY THIS IS DETERMINISTIC AND NOT AI-DRIVEN
    This is the most important design decision in the project. The AI component
    of this tool (see ai_summary.py) writes explanations. It does NOT decide
    whether a message is malicious.

    The reason is evidentiary. A language model produces different output for
    identical input across runs, cannot fully explain how it reached a
    conclusion, and cannot be cross-examined. A rule-based score can be
    recomputed by anyone, produces the same answer every time, and every point
    it assigns traces back to a specific named rule in this file. If a finding
    is disputed, an examiner can point at the exact line of code that produced
    it.

    So: rules score, AI explains. The written report discusses this at length.

SCORING MODEL
    Each finding contributes points based on severity:
        high    = 40 points
        medium  = 12 points
        low     = 4 points

    Certain combinations are weighted extra, because signals that are weak
    alone become strong together. A high-risk TLD is unremarkable; a high-risk
    TLD on a link whose anchor text claims to be a bank, in a message that
    failed DMARC, is not.

    The total is capped at 100 and mapped to a band. The thresholds below were
    chosen so that any single high-severity finding lands at minimum in
    SUSPICIOUS, and two independent high-severity findings reach MALICIOUS.

------------------------------------------------------------------------------
AI GENERATION NOTICE
    This file was generated by Claude Opus 5 (Anthropic) at the request of the
    project authors, then reviewed and adapted by the authors. See the AI Usage
    Disclosure section of README.md for the project's full position on AI use.
------------------------------------------------------------------------------

Project: IT 360 Final Project -- Phishing Email Forensics Analyzer
Authors: Tyler and Sam
"""

# Points awarded per finding severity.
#
# These values are calibrated against the RISK_BANDS thresholds below so that:
#   - one high finding (40)            -> SUSPICIOUS  (threshold 40)
#   - two high findings (80)           -> MALICIOUS   (threshold 70)
#   - three medium findings (36)       -> QUESTIONABLE
# Changing either these points or the thresholds requires re-checking those
# relationships. test_analyzer.py asserts them so a mismatch fails loudly.
SEVERITY_POINTS = {
    "high": 40,
    "medium": 12,
    "low": 4,
}

# Risk bands, evaluated from the top down.
RISK_BANDS = [
    (70, "MALICIOUS",  "Multiple strong indicators of a phishing attempt. "
                       "Treat as hostile: do not interact, and escalate "
                       "according to your incident response process."),
    (40, "SUSPICIOUS", "Significant indicators present. Manual review by an "
                       "analyst is warranted before any user is permitted to "
                       "interact with this message."),
    (15, "QUESTIONABLE", "Some indicators present, none conclusive. Context "
                         "about the sender and the recipient's expectations "
                         "is needed to reach a determination."),
    (0,  "LOW RISK",   "No significant indicators detected. Note that absence "
                       "of indicators is not proof of legitimacy -- a "
                       "well-constructed phish may produce no findings."),
]

# Finding-code pairs that reinforce each other. When both codes appear in the
# same message, the bonus is added once.
CORRELATION_BONUSES = [
    (
        {"DMARC_FAIL", "SPF_FAIL", "DKIM_FAIL"},
        {"ANCHOR_TEXT_MISMATCH", "LOOKALIKE_DOMAIN", "DISPLAY_NAME_ADDRESS_SPOOF"},
        15,
        "Authentication failure combined with visual deception in the message body.",
    ),
    (
        {"REPLYTO_MISMATCH"},
        {"CORPORATE_NAME_FREE_MAIL", "DISPLAY_NAME_ADDRESS_SPOOF"},
        10,
        "Sender impersonation combined with redirected replies.",
    ),
    (
        {"DANGEROUS_EXTENSION", "DOUBLE_EXTENSION", "FILE_TYPE_MISMATCH"},
        {"DMARC_FAIL", "SPF_FAIL", "DKIM_FAIL", "LOOKALIKE_DOMAIN"},
        15,
        "Executable attachment delivered from an unauthenticated or "
        "impersonating sender.",
    ),
    (
        {"HIGH_RISK_TLD", "URL_SHORTENER"},
        {"CREDENTIAL_KEYWORDS_IN_PATH"},
        8,
        "Obscured link destination pointing at a credential-collection path.",
    ),
]


def score_findings(findings):
    """Compute a risk score and band from a list of findings.

    Args:
        findings (list[dict]): All findings from all analysis modules. Each
            must have "code" and "severity" keys.

    Returns:
        dict: {
            "score": int,              0-100
            "band": str,               e.g. "MALICIOUS"
            "guidance": str,           What to do about it
            "base_points": int,        Points from individual findings
            "bonus_points": int,       Points from correlations
            "counts": dict,            {"high": n, "medium": n, "low": n}
            "correlations": list[str], Which bonuses fired and why
        }
    """
    counts = {"high": 0, "medium": 0, "low": 0}
    base_points = 0

    for finding in findings:
        severity = finding.get("severity", "low").lower()
        if severity not in SEVERITY_POINTS:
            severity = "low"
        counts[severity] += 1
        base_points += SEVERITY_POINTS[severity]

    # --- Correlation bonuses ------------------------------------------------
    present_codes = {f.get("code", "") for f in findings}
    bonus_points = 0
    correlations = []

    for group_a, group_b, points, explanation in CORRELATION_BONUSES:
        if present_codes & group_a and present_codes & group_b:
            bonus_points += points
            correlations.append(explanation)

    total = min(base_points + bonus_points, 100)

    # --- Map to a band ------------------------------------------------------
    band = RISK_BANDS[-1][1]
    guidance = RISK_BANDS[-1][2]
    for threshold, band_name, band_guidance in RISK_BANDS:
        if total >= threshold:
            band = band_name
            guidance = band_guidance
            break

    return {
        "score": total,
        "band": band,
        "guidance": guidance,
        "base_points": base_points,
        "bonus_points": bonus_points,
        "counts": counts,
        "correlations": correlations,
    }
