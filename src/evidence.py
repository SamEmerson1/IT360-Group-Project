import hashlib
import os
from datetime import datetime, timezone

# Reading the file in fixed-size chunks rather than all at once keeps memory
# usage flat regardless of file size. 64 KB is a common compromise between
# syscall overhead and memory footprint.
_CHUNK_SIZE = 65536


def compute_hashes(path):
    """Compute MD5 and SHA-256 digests of a file without loading it into memory.

    Args:
        path (str): Path to the file to hash.

    Returns:
        dict: {"md5": <hex>, "sha256": <hex>, "size_bytes": <int>}

    Raises:
        FileNotFoundError: If the path does not exist.
        PermissionError: If the file cannot be read.
    """
    md5 = hashlib.md5()
    sha256 = hashlib.sha256()
    size = 0

    # "rb" -- binary, read-only. We never open evidence in a writable mode.
    with open(path, "rb") as handle:
        while True:
            chunk = handle.read(_CHUNK_SIZE)
            if not chunk:
                break
            size += len(chunk)
            md5.update(chunk)
            sha256.update(chunk)

    return {
        "md5": md5.hexdigest(),
        "sha256": sha256.hexdigest(),
        "size_bytes": size,
    }


def hash_bytes(data):
    """Compute MD5 and SHA-256 digests of an in-memory bytes object.

    Used for hashing email attachments, which are extracted into memory
    rather than written to disk. We deliberately avoid writing attachments
    out, since some of them may be live malware.

    Args:
        data (bytes): The raw bytes to hash.

    Returns:
        dict: {"md5": <hex>, "sha256": <hex>, "size_bytes": <int>}
    """
    return {
        "md5": hashlib.md5(data).hexdigest(),
        "sha256": hashlib.sha256(data).hexdigest(),
        "size_bytes": len(data),
    }


def utc_now():
    """Return the current UTC time as an ISO 8601 string.

    All timestamps this tool produces are UTC. Local time zones are a common
    source of confusion in forensic timelines, especially when evidence crosses
    jurisdictions, so we normalize everything to UTC and label it explicitly.
    """
    return datetime.now(timezone.utc).isoformat()


class AuditLog:
    """Append-only, timestamped record of every action taken during analysis.

    Usage:
        log = AuditLog("reports/audit.log")
        log.record("ANALYSIS_START", "Beginning analysis of sample.eml")
        ...
        log.close()

    Each entry is written to disk immediately (the file handle is flushed after
    every write) so that if the tool crashes partway through, the log still
    reflects everything that happened up to the crash.
    """

    def __init__(self, path=None, echo=False):
        """
        Args:
            path (str | None): Where to write the log. If None, entries are
                kept in memory only. Useful for testing.
            echo (bool): If True, also print each entry to stdout as it is
                recorded. Handy during a live demo.
        """
        self.path = path
        self.echo = echo
        self.entries = []
        self._handle = None

        if path:
            # Make sure the parent directory exists before we try to write.
            parent = os.path.dirname(os.path.abspath(path))
            os.makedirs(parent, exist_ok=True)
            self._handle = open(path, "a", encoding="utf-8")
            self._write_line(
                "=" * 78 + "\n"
                f"Audit log opened {utc_now()}\n"
                "Phishing Email Forensics Analyzer -- IT 360\n"
                + "=" * 78 + "\n"
            )

    def _write_line(self, text):
        """Write raw text to the log file and flush immediately."""
        if self._handle:
            self._handle.write(text)
            self._handle.flush()

    def record(self, action, detail=""):
        """Record a single audit entry.

        Args:
            action (str): Short uppercase action code, e.g. "HASH_COMPUTED".
                Keeping these to a controlled vocabulary makes the log
                greppable and easier to parse later.
            detail (str): Free-text description of what happened.
        """
        entry = {
            "timestamp": utc_now(),
            "action": action,
            "detail": detail,
        }
        self.entries.append(entry)

        line = f"[{entry['timestamp']}] {action}: {detail}\n"
        self._write_line(line)

        if self.echo:
            print(f"  [audit] {action}: {detail}")

    def close(self):
        """Close the log file. Safe to call more than once."""
        if self._handle:
            self._write_line(f"Audit log closed {utc_now()}\n\n")
            self._handle.close()
            self._handle = None

    # Supporting the context-manager protocol means callers can write
    #     with AuditLog("audit.log") as log:
    # and be guaranteed the file gets closed even if an exception is raised.
    def __enter__(self):
        return self

    def __exit__(self, exc_type, exc_value, traceback):
        if exc_type is not None:
            self.record("ERROR", f"{exc_type.__name__}: {exc_value}")
        self.close()
        return False  # Do not suppress the exception.


def verify_integrity(before, after):
    """Compare two hash dictionaries and report whether the evidence changed.

    Args:
        before (dict): Output of compute_hashes() taken before analysis.
        after (dict): Output of compute_hashes() taken after analysis.

    Returns:
        dict: {"verified": bool, "message": str}
    """
    matched = (
        before.get("sha256") == after.get("sha256")
        and before.get("md5") == after.get("md5")
        and before.get("size_bytes") == after.get("size_bytes")
    )

    if matched:
        message = "Evidence file unchanged. Pre- and post-analysis hashes match."
    else:
        # This should never happen given that we only ever open in "rb" mode.
        # If it does, something outside this tool modified the file mid-run,
        # and every finding in the report is suspect.
        message = (
            "INTEGRITY FAILURE: evidence hashes do not match. The file was "
            "modified during analysis. Findings in this report cannot be relied "
            "upon."
        )

    return {"verified": matched, "message": message}
