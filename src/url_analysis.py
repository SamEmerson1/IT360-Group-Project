# TLDs that see disproportionate abuse, largely because registration is free or
# near-free. Presence here is a weak signal on its own -- plenty of legitimate
# sites use these -- so findings are scored as medium rather than high.
HIGH_RISK_TLDS = {
    "tk", "ml", "ga", "cf", "gq",          # Freenom-operated, historically free
    "xyz", "top", "buzz", "click", "link",
    "work", "country", "kim", "science",
    "party", "gdn", "review", "date",
    "loan", "men", "stream", "download",
    "zip", "mov",                          # Confusable with file extensions
}

# URL shorteners hide the true destination. Not malicious in themselves, but
# their use in unsolicited mail is worth flagging because it defeats visual
# inspection of the link.
URL_SHORTENERS = {
    "bit.ly", "tinyurl.com", "goo.gl", "t.co", "ow.ly", "is.gd",
    "buff.ly", "adf.ly", "bit.do", "cutt.ly", "rebrand.ly", "shorturl.at",
    "tiny.cc", "rb.gy", "s.id", "t.ly", "short.io",
}

# Plain-text URL extraction. Deliberately conservative: it will miss exotic
# schemes, but it does not produce the flood of false positives that a very
# permissive pattern generates on HTML-heavy mail.
_URL_PATTERN = re.compile(
    r"""(?xi)
    \b
    (?:https?://|www\.)          # scheme, or a bare www. host
    [^\s<>"'\)\]\}]+             # everything up to whitespace or a delimiter
    """
)

# Trailing punctuation that is almost always sentence punctuation rather than
# part of the URL itself.
_TRAILING_JUNK = ".,;:!?)]}>\"'"


class _AnchorExtractor(HTMLParser):
    """Collect (href, visible_text) pairs from HTML anchor tags.

    We use the standard library's HTMLParser rather than adding BeautifulSoup
    as a dependency. HTMLParser is tolerant of malformed markup, which matters
    because phishing HTML is frequently broken -- sometimes deliberately, to
    confuse filters that expect well-formed documents.
    """

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.anchors = []          # Completed (href, text) pairs
        self._current_href = None
        self._current_text = []

    def handle_starttag(self, tag, attrs):
        if tag.lower() != "a":
            return
        attributes = dict(attrs)
        href = attributes.get("href")
        if href:
            self._current_href = href
            self._current_text = []

    def handle_data(self, data):
        if self._current_href is not None:
            self._current_text.append(data)

    def handle_endtag(self, tag):
        if tag.lower() != "a" or self._current_href is None:
            return
        text = " ".join("".join(self._current_text).split())
        self.anchors.append((self._current_href, text))
        self._current_href = None
        self._current_text = []

    def error(self, message):
        # HTMLParser's base class declares this; we swallow errors so that
        # malformed markup never aborts the analysis.
        pass


