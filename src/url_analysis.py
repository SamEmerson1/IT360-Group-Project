def defang(url):
    """Render a URL safe to display in reports and ticketing systems.

    Transformations:
        http   -> hxxp
        https  -> hxxps
        .      -> [.]        (in the host portion only)
        @      -> [@]

    We defang dots only in the host, not the whole URL, so that file paths and
    query strings stay readable.
    """
    if not url:
        return ""

    working = url.replace("https://", "hxxps://").replace("http://", "hxxp://")

    # Split off the host so we only defang dots there.
    match = re.match(r"^(hxxps?://)([^/?#]+)(.*)$", working, re.IGNORECASE)
    if match:
        scheme, host, remainder = match.groups()
        host = host.replace(".", "[.]").replace("@", "[@]")
        return f"{scheme}{host}{remainder}"

    # Bare hostname with no scheme.
    return working.replace(".", "[.]").replace("@", "[@]")


def unwrap_url(url):
    """Recover the original URL from a mail-security rewrite wrapper.

    Returns:
        tuple: (unwrapped_url, wrapper_name | None)

    Supported wrappers:
        Microsoft Defender Safe Links   -- *.safelinks.protection.outlook.com
        Proofpoint URL Defense          -- urldefense.com / urldefense.proofpoint.com
        Google redirect                 -- google.com/url?q=

    Unwrapping is done purely by reading the wrapper's query parameters. No
    request is made to the wrapper service.
    """
    if not url:
        return url, None

    try:
        parsed = urlparse(url)
    except ValueError:
        return url, None

    host = (parsed.hostname or "").lower()
    query = parse_qs(parsed.query)

    # --- Microsoft Safe Links -----------------------------------------------
    if "safelinks.protection.outlook.com" in host:
        target = query.get("url", [None])[0]
        if target:
            return unquote(target), "Microsoft Safe Links"

    # --- Google redirect ----------------------------------------------------
    if host.endswith("google.com") and parsed.path.startswith("/url"):
        target = query.get("q", query.get("url", [None]))[0]
        if target:
            return unquote(target), "Google redirect"

    # --- Proofpoint URL Defense ---------------------------------------------
    if "urldefense" in host:
        # v2 uses ?u= with a lightly substituted encoding.
        target = query.get("u", [None])[0]
        if target:
            decoded = unquote(target).replace("-", "%").replace("_", "/")
            return unquote(decoded), "Proofpoint URL Defense (v2)"

        # v3 embeds the URL in the path: /v3/__<url>__;...
        v3 = re.search(r"/v3/__(.+?)__", parsed.path + "?" + parsed.query)
        if v3:
            return unquote(v3.group(1)), "Proofpoint URL Defense (v3)"

    return url, None


def extract_urls(parsed_email):
    """Pull every URL out of the message bodies.

    Returns:
        list[dict]: One entry per unique URL, containing:
            url            -- the URL as found, after unwrapping
            original       -- the URL before unwrapping (if it differed)
            wrapper        -- name of the rewrite service, or None
            anchor_text    -- visible link text, for HTML anchors
            source         -- "html_anchor", "html_body", or "text_body"
    """
    found = {}   # Keyed by URL so we deduplicate while preserving first-seen data

    def _add(url, anchor_text, source):
        url = url.strip().rstrip(_TRAILING_JUNK)
        if not url:
            return
        # Normalize bare www. hosts to a full URL so parsing works downstream.
        if url.lower().startswith("www."):
            url = "http://" + url

        unwrapped, wrapper = unwrap_url(url)
        key = unwrapped

        if key in found:
            # Keep anchor text if we did not have any before.
            if anchor_text and not found[key]["anchor_text"]:
                found[key]["anchor_text"] = anchor_text
            return

        found[key] = {
            "url": unwrapped,
            "original": url if wrapper else None,
            "wrapper": wrapper,
            "anchor_text": anchor_text,
            "source": source,
        }

    html_body = parsed_email["bodies"].get("html")
    text_body = parsed_email["bodies"].get("text")

    # --- HTML anchors (highest fidelity: we get href AND visible text) ------
    if html_body:
        extractor = _AnchorExtractor()
        try:
            extractor.feed(html_body)
            extractor.close()
        except Exception:
            # Malformed markup. We keep whatever anchors were parsed before the
            # failure and fall through to regex extraction for the rest.
            pass

        for href, text in extractor.anchors:
            if href.lower().startswith(("mailto:", "tel:", "#", "javascript:")):
                continue
            _add(href, text, "html_anchor")

        # Also regex the raw HTML to catch URLs that are not inside anchors --
        # image sources, CSS backgrounds, and plain text within the markup.
        for match in _URL_PATTERN.findall(html_body):
            _add(match, "", "html_body")

    # --- Plain-text body ----------------------------------------------------
    if text_body:
        for match in _URL_PATTERN.findall(text_body):
            _add(match, "", "text_body")

    return list(found.values())


def evaluate_url(entry):
    """Apply suspicion checks to a single extracted URL.

    Args:
        entry (dict): One item from extract_urls().

    Returns:
        list[dict]: Findings for this URL.
    """
    findings = []
    url = entry["url"]

    try:
        parsed = urlparse(url)
    except ValueError:
        return [{
            "code": "MALFORMED_URL",
            "severity": "low",
            "title": "URL could not be parsed",
            "detail": f"The string '{defang(url)}' was extracted as a URL but "
                      f"could not be parsed as one.",
        }]

    host = (parsed.hostname or "").lower()
    registrable = _registrable_domain(host)
    tld = host.rsplit(".", 1)[-1] if "." in host else ""

    # --- Anchor text claims a different destination -------------------------
    # The classic visual deception: the link reads "paypal.com" but points
    # somewhere else entirely.
    anchor = entry.get("anchor_text") or ""
    anchor_urls = _URL_PATTERN.findall(anchor)
    if anchor_urls:
        for candidate in anchor_urls:
            candidate_host = ""
            try:
                normalized = candidate if "://" in candidate else "http://" + candidate
                candidate_host = (urlparse(normalized).hostname or "").lower()
            except ValueError:
                continue
            if candidate_host and _registrable_domain(candidate_host) != registrable:
                findings.append({
                    "code": "ANCHOR_TEXT_MISMATCH",
                    "severity": "high",
                    "title": "Link text does not match the link destination",
                    "detail": (
                        f"The visible link text reads '{candidate}' but the "
                        f"link actually points to {defang(url)}. The recipient "
                        f"sees one destination and is sent to another."
                    ),
                })

    # --- Raw IP address instead of a hostname -------------------------------
    if re.match(r"^\d{1,3}(\.\d{1,3}){3}$", host):
        findings.append({
            "code": "IP_LITERAL_URL",
            "severity": "high",
            "title": "Link points to a raw IP address",
            "detail": (
                f"The URL {defang(url)} uses the IP address {host} directly "
                f"rather than a hostname. Legitimate services publish DNS "
                f"names; direct IP links are typical of disposable "
                f"attacker-controlled infrastructure."
            ),
        })

    # --- Credentials embedded in the URL ------------------------------------
    # Format: https://legitimate-looking-part@actual-destination.com
    # Browsers treat everything before the @ as credentials and navigate to
    # what follows, but a reader scanning quickly sees the part before it.
    if parsed.username or "@" in (parsed.netloc or ""):
        findings.append({
            "code": "URL_EMBEDDED_CREDENTIALS",
            "severity": "high",
            "title": "URL contains an @ symbol in the authority section",
            "detail": (
                f"The URL {defang(url)} places text before an '@' in the host "
                f"portion. Browsers interpret that text as credentials and "
                f"navigate to whatever follows the '@', so the visible "
                f"beginning of the URL is not the destination."
            ),
        })

    # --- Punycode -----------------------------------------------------------
    if "xn--" in host:
        findings.append({
            "code": "PUNYCODE_URL",
            "severity": "high",
            "title": "URL host uses punycode encoding",
            "detail": (
                f"The host '{host}' is punycode-encoded and contains non-ASCII "
                f"characters that may render as a familiar brand name."
            ),
        })

    # --- Non-standard port --------------------------------------------------
    if parsed.port and parsed.port not in (80, 443):
        findings.append({
            "code": "NONSTANDARD_PORT",
            "severity": "medium",
            "title": f"URL specifies non-standard port {parsed.port}",
            "detail": (
                f"The URL {defang(url)} connects on port {parsed.port} rather "
                f"than the usual 80 or 443. This is common on hosts running "
                f"ad-hoc services rather than production web infrastructure."
            ),
        })

    # --- High-risk TLD ------------------------------------------------------
    if tld in HIGH_RISK_TLDS:
        findings.append({
            "code": "HIGH_RISK_TLD",
            "severity": "medium",
            "title": f"Link uses the '.{tld}' top-level domain",
            "detail": (
                f"The host '{host}' uses '.{tld}', a TLD with elevated abuse "
                f"rates due to free or very low-cost registration. This is a "
                f"weak signal on its own but meaningful in combination with "
                f"other findings."
            ),
        })

    # --- URL shortener ------------------------------------------------------
    if registrable in URL_SHORTENERS:
        findings.append({
            "code": "URL_SHORTENER",
            "severity": "medium",
            "title": f"Link uses the URL shortener {registrable}",
            "detail": (
                f"The URL {defang(url)} routes through a shortening service, "
                f"which conceals the true destination from visual inspection. "
                f"Resolve it in an isolated environment before assessing it."
            ),
        })

    # --- Lookalike domain ---------------------------------------------------
    for finding in check_lookalike_domain(host):
        finding = dict(finding)
        finding["title"] = f"Link host: {finding['title']}"
        findings.append(finding)

    # --- Credential-harvesting keywords in the path -------------------------
    path_and_query = (parsed.path + "?" + (parsed.query or "")).lower()
    credential_terms = ["login", "signin", "verify", "account", "secure",
                        "update", "confirm", "password", "auth", "billing"]
    matched = [t for t in credential_terms if t in path_and_query]
    if matched and registrable not in ("microsoft.com", "google.com", "apple.com"):
        findings.append({
            "code": "CREDENTIAL_KEYWORDS_IN_PATH",
            "severity": "low",
            "title": "URL path contains credential-related keywords",
            "detail": (
                f"The path of {defang(url)} contains: {', '.join(matched)}. "
                f"Credential-harvesting pages commonly mimic login flows in "
                f"their URL structure. This alone is not conclusive."
            ),
        })

    return findings


def analyze_urls(parsed_email, audit_log=None):
    """Run the full URL analysis pipeline.

    Returns:
        dict: {
            "urls": [ ...entries with a "findings" key added... ],
            "findings": [ ...all findings, flattened... ],
        }
    """
    if audit_log:
        audit_log.record("URL_ANALYSIS_START", "Extracting URLs from message bodies")

    entries = extract_urls(parsed_email)
    all_findings = []

    for entry in entries:
        entry_findings = evaluate_url(entry)
        entry["findings"] = entry_findings
        entry["defanged"] = defang(entry["url"])
        all_findings.extend(entry_findings)

        if entry["wrapper"] and audit_log:
            audit_log.record(
                "URL_UNWRAPPED",
                f"Unwrapped {entry['wrapper']} link to {entry['defanged']}",
            )

    if audit_log:
        audit_log.record(
            "URL_ANALYSIS_COMPLETE",
            f"{len(entries)} unique URL(s), {len(all_findings)} finding(s)",
        )

    return {"urls": entries, "findings": all_findings}
