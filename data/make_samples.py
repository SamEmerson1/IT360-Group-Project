# ---------------------------------------------------------------------------
# 04 -- Malicious attachment
# ---------------------------------------------------------------------------
# Exercises: DOUBLE_EXTENSION, DANGEROUS_EXTENSION, FILE_TYPE_MISMATCH,
# plus authentication failures.
#
# The attachment payload is the two-byte "MZ" DOS header followed by filler.
# That is enough for the analyzer's magic-byte check to identify it as a
# Windows executable. It is not, and cannot be, a functioning program --
# it has no PE header, no entry point, and no code. It is inert filler.

